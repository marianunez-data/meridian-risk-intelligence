-- Gold: loan-level fact table. Grain = one funded loan.
-- Foreign keys: issue_month -> dim_month, sub_grade -> dim_risk_grade,
-- state_code -> dim_geography.
select
    loan_id,
    issue_month,
    sub_grade,
    state_code,
    grade,
    term_months,
    loan_purpose,
    home_ownership,
    income_verification,
    application_type,
    funded_amount,
    interest_rate,
    installment_amount,
    annual_income,
    fico_score,
    debt_to_income,
    loan_status,
    is_policy_exception,
    is_resolved,
    is_defaulted,
    is_bad_24m,
    has_full_window,
    months_observed,
    months_to_default,
    est_default_month,
    exposure_at_default,
    net_recoveries,
    loss_given_default,
    has_seasoned_recovery,
    principal_repaid,
    interest_received,
    late_fees_received,
    total_payments,
    -- Realised profit to date for the investor: everything received minus principal lent.
    total_payments - funded_amount                    as realised_net_cash,
    dataset_split
from {{ ref('int_loans__outcomes') }}
